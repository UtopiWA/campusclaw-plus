import { mount, flushPromises } from '@vue/test-utils'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
vi.mock('../services/learning.js', () => ({ getLearningPlan: vi.fn(), generateLearningPlan: vi.fn(), completeLearningTask: vi.fn() }))
import LearningPlan from './LearningPlan.vue'
import { completeLearningTask, generateLearningPlan, getLearningPlan } from '../services/learning.js'
import { clearFeedback, feedbackMessages } from '../services/feedback.js'
let wrapper
const task = (id, type) => ({ id, title: '方程学习', type, day: 1, minutes: 15, instruction: '先整理数量关系', status: 'PENDING', resources: { materials: [], questions: type === 'PRACTICE' ? [{ id: 5, title: '实际练习题' }] : [], unavailable: false } })
const plan = (tasks = []) => ({ id: 1, revision: 1, goal: '应用题列式', days: 3, dailyMinutes: 30, tasks, message: '先复习再练习', history: [{ summary: '不展示的历史' }], handoffs: [{ outputSummary: '不展示的依据' }] })
const view = () => (wrapper = mount(LearningPlan, { global: { stubs: { RouterLink: { props: ['to'], template: '<a :href="to"><slot /></a>' } } } }))
beforeEach(() => { vi.clearAllMocks(); clearFeedback(); getLearningPlan.mockResolvedValue({}) })
afterEach(() => { wrapper?.unmount(); clearFeedback() })
it.each([0, 1, 10])('keeps the default pager visible for a saved plan with %s tasks', async (count) => {
  getLearningPlan.mockResolvedValue(plan(Array.from({ length: count }, (_, index) => task(index + 1, 'REVIEW'))))
  const w = view(); await flushPromises()
  const pager = w.find('[aria-label="计划任务分页"]')
  expect(pager.text()).toContain(`共 ${count} 条`)
  expect(pager.text()).toContain('1 / 1')
  expect(pager.find('select').element.value).toBe('10')
  expect(pager.findAll('option').map(option => option.element.value)).toEqual(['10', '20', '50'])
  expect(pager.findAll('button').every(button => button.element.disabled)).toBe(true)
})
it('does not show a task pager before any plan exists', async () => {
  const w = view(); await flushPromises()
  expect(w.find('[aria-label="计划任务分页"]').exists()).toBe(false)
})
it('starts with an optional empty goal instead of copying a previous goal', async () => {
  getLearningPlan.mockResolvedValue(plan())
  generateLearningPlan.mockResolvedValue(plan())
  const w = view(); await flushPromises()
  expect(w.find('input[maxlength="200"]').element.value).toBe('')
  expect(w.text()).toContain('目标：应用题列式')
  await w.findAll('input[type=number]')[0].setValue('7')
  await w.find('form').trigger('submit'); await flushPromises()
  expect(generateLearningPlan).toHaveBeenCalledWith({ goal: '', days: 7, dailyMinutes: 30 }, expect.any(Object))
})
it('uses seven days and thirty minutes when no plan exists', async () => {
  generateLearningPlan.mockResolvedValue(plan())
  const w = view(); await flushPromises()
  expect(w.findAll('input[type=number]').map(input => input.element.value)).toEqual(['7', '30'])
  await w.find('form').trigger('submit'); await flushPromises()
  expect(generateLearningPlan).toHaveBeenCalledWith({ goal: '', days: 7, dailyMinutes: 30 }, expect.any(Object))
})
it.each([[0, '-1'], [0, '0'], [0, '15'], [0, '1.5'], [0, ''], [1, '-30'], [1, '9'], [1, '121'], [1, '30.5'], [1, '']])('warns on blur and rejects invalid budget input %s=%s', async (index, value) => {
  const w = view(); await flushPromises()
  const input = w.findAll('input[type=number]')[index]
  await input.setValue(value)
  await input.trigger('blur')
  expect(input.attributes('aria-invalid')).toBe('true')
  expect(feedbackMessages.value.at(-1).message).toContain('整数')
  await w.find('form').trigger('submit'); await flushPromises()
  expect(generateLearningPlan).not.toHaveBeenCalled()
})
it('renders plan messages and task instructions as safe Markdown and math', async () => {
  getLearningPlan.mockResolvedValue({ ...plan([{ ...task(1, 'REVIEW'), instruction: '先练习：\\[x^2=9\\]，再复习。' }]), message: '## 安排\n\n复习 $x=3$。<img src=x onerror=alert(1)>' })
  const w = view(); await flushPromises()
  expect(w.find('h2').text()).toBe('学习计划')
  expect(w.findAll('.assistant-markdown h2')).toHaveLength(1)
  expect(w.findAll('.assistant-markdown .katex')).toHaveLength(2)
  expect(w.find('.assistant-markdown img').exists()).toBe(false)
})
it('only generates on request and sends the goal and time budget together', async () => {
  generateLearningPlan.mockResolvedValue(plan([task(1, 'REVIEW')]))
  const w = view(); await flushPromises()
  expect(generateLearningPlan).not.toHaveBeenCalled()
  await w.find('input[maxlength="200"]').setValue('应用题列式')
  await w.findAll('input[type=number]')[0].setValue('3')
  await w.find('form').trigger('submit'); await flushPromises()
  expect(generateLearningPlan).toHaveBeenCalledWith({ goal: '应用题列式', days: 3, dailyMinutes: 30 }, expect.any(Object))
  expect(w.text()).toContain('第 1 天 · 约 15 分钟')
  expect(w.text()).not.toMatch(/调整历史|安排依据|补充学习建议|不展示的/)
})
it('links to specific questions and only permits manually completing a reading task', async () => {
  getLearningPlan.mockResolvedValue(plan([task(1, 'REVIEW'), task(2, 'PRACTICE')]))
  completeLearningTask.mockResolvedValue(plan([{ ...task(1, 'REVIEW'), status: 'DONE' }, task(2, 'PRACTICE')]))
  const w = view(); await flushPromises()
  expect(w.find('a').attributes('href')).toBe('/questions/5')
  expect(w.findAll('button').filter((b) => b.text() === '标记完成')).toHaveLength(1)
  await w.findAll('button').find((b) => b.text() === '标记完成').trigger('click'); await flushPromises()
  expect(completeLearningTask).toHaveBeenCalledWith(1, 1, expect.any(Object))
  expect(w.text()).toContain('已完成')
  expect(w.findAll('button').filter((b) => b.text() === '标记完成')).toHaveLength(0)
})
it('keeps the existing tasks and edited goal after a model failure', async () => {
  getLearningPlan.mockResolvedValue(plan([task(1, 'REVIEW')]))
  generateLearningPlan.mockRejectedValue(new Error('生成失败，原计划保留'))
  const w = view(); await flushPromises()
  await w.find('input[maxlength="200"]').setValue('新的目标')
  await w.find('form').trigger('submit'); await flushPromises()
  expect(w.text()).toContain('方程学习')
  expect(w.find('input[maxlength="200"]').element.value).toBe('新的目标')
  expect(feedbackMessages.value.at(-1).message).toContain('原计划保留')
})
it('validates budgets and paginates task lists', async () => {
  getLearningPlan.mockResolvedValue(plan(Array.from({ length: 14 }, (_, i) => task(i + 1, 'REVIEW'))))
  const w = view(); await flushPromises()
  expect(w.findAll('.plan-task-list li')).toHaveLength(10)
  await w.find('[aria-label="计划任务分页"]').findAll('button')[1].trigger('click')
  expect(w.findAll('.plan-task-list li')).toHaveLength(4)
  await w.findAll('input[type=number]')[0].setValue('15')
  await w.find('form').trigger('submit'); await flushPromises()
  expect(generateLearningPlan).not.toHaveBeenCalled()
  expect(feedbackMessages.value.at(-1).message).toContain('1至14')
})
